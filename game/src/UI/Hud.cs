    {
        _parryFlash = new ColorRect
        {
            Name = "ParryFlash",
            Color = new Color(1f, 0.9f, 0.45f, 0f),
            Visible = false,
            MouseFilter = MouseFilterEnum.Ignore,
        };
        _parryFlash.SetAnchorsPreset(LayoutPreset.FullRect);
