    /// <summary>
    /// The heat bar and its two threshold marks.
    ///
    /// Built in code and parented to the HUD ROOT rather than to the health
    /// bar's parent, then positioned from the health bar's global rect every
    /// frame. The health bar comes from Hud.tscn and this file does not get to
    /// assume what contains it -- a Control inside a Container has its Position
    /// overwritten by the layout, and a bar that silently snaps to the corner
    /// is the kind of thing nobody notices until a screenshot.
    ///
    /// The ticks are children of the bar. A player has to know WHERE the rules
    /// change, not merely that they do: without the marks at 40 and 70 the
    /// colour shifts are something that happens TO you.
    /// </summary>
    private void BuildHeatBar()
    {
        _heatFill = new StyleBoxFlat { BgColor = HeatColors[0] };

        _heatBar = new ProgressBar
        {
            Name = "HeatBar",
            Visible = false,
            MinValue = 0,
            MaxValue = 100,
            Value = 0,
            ShowPercentage = false,
            MouseFilter = MouseFilterEnum.Ignore,
        };
        _heatBar.SetAnchorsPreset(LayoutPreset.TopLeft);
        _heatBar.AddThemeStyleboxOverride("fill", _heatFill);
        _heatBar.AddThemeStyleboxOverride("background", new StyleBoxFlat
        {
            BgColor = new Color(0.10f, 0.07f, 0.06f, 0.85f),
        });
        AddChild(_heatBar);

        _heatTick40 = BuildTick();
        _heatTick70 = BuildTick();
    }

    private ColorRect BuildTick()
    {
        var tick = new ColorRect
        {
            Name = "HeatTick",
            Color = new Color(0.06f, 0.05f, 0.04f, 0.9f),
            MouseFilter = MouseFilterEnum.Ignore,
        };
        _heatBar.AddChild(tick);
        return tick;
    }

    /// <summary>
    /// Four pips beside the health bar. They light one at a time as perfect
    /// parries chain and all go dark together on any damage, which is exactly
    /// what the streak does -- the row is the rule, drawn.
    /// </summary>
    private void BuildStreakPips()
    {
        _streakPips = new ColorRect[StreakPips];
        for (int i = 0; i < StreakPips; i++)
        {
            _streakPips[i] = new ColorRect
            {
                Name = $"StreakPip{i}",
                Color = PipColor(false),
                Visible = false,
                MouseFilter = MouseFilterEnum.Ignore,
            };
            _streakPips[i].SetAnchorsPreset(LayoutPreset.TopLeft);
            AddChild(_streakPips[i]);
        }
    }

    private static Color PipColor(bool lit) => lit
        ? new Color(1f, 0.86f, 0.38f, 0.95f)
        : new Color(0.30f, 0.24f, 0.20f, 0.55f);

    /// <summary>
    /// The two mood overlays, built once.
    ///
    /// They are added BEFORE the flashover flash in z-order terms only by
    /// virtue of being added after it in _Ready -- Godot draws siblings in
    /// child order, so the last one added is on top. The white-hot flash is a
    /// momentary event and must sit over the moods, so it is created first and
    /// these two go above... which is the wrong way round, and is why both of
    /// these explicitly move themselves BELOW it.
    /// </summary>
    private void BuildTensionOverlays()
    {
        _lowHealthVignette = BuildRadialOverlay("LowHealthVignette", LowHealthColor, edgeStop: 0.42f);
        _flashoverEdge = BuildRadialOverlay("FlashoverEdge", FlashoverEdgeColor, edgeStop: 0.62f);

        // Under the flash, over everything else. A vignette drawn on top of the
        // flashover's own white-out would tint the one frame that is supposed
        // to be pure light.
        if (_flashoverFlash != null)
        {
            MoveChild(_lowHealthVignette, _flashoverFlash.GetIndex());
            MoveChild(_flashoverEdge, _flashoverFlash.GetIndex());
        }
    }

    /// <summary>
    /// A full-screen radial gradient: clear in the middle, coloured at the
    /// edges. Generated by the engine from a handful of numbers rather than
    /// imported, which keeps the no-external-assets rule and leaves the falloff
    /// tunable without an image editor.
    /// </summary>
    /// <param name="edgeStop">Where the colour starts coming in, 0 at the
    /// centre and 1 at the corner. Higher is a tighter frame around the edge.</param>
    private TextureRect BuildRadialOverlay(string name, Color tint, float edgeStop)
    {
        var gradient = new Gradient
        {
            Offsets = new[] { 0f, edgeStop, 1f },
            Colors = new[]
            {
                new Color(tint.R, tint.G, tint.B, 0f),
                new Color(tint.R, tint.G, tint.B, 0f),
                new Color(tint.R, tint.G, tint.B, 1f),
            },
        };

        var texture = new GradientTexture2D
        {
            Gradient = gradient,
            Width = 256,
            Height = 256,
            Fill = GradientTexture2D.FillEnum.Radial,
            FillFrom = new Vector2(0.5f, 0.5f),
            FillTo = new Vector2(1.0f, 0.5f),
        };

        var rect = new TextureRect
        {
            Name = name,
            Texture = texture,
            // Stretched to whatever the window is. The gradient is 256x256 and
            // is meant to be smeared: it has no detail to lose.
            StretchMode = TextureRect.StretchModeEnum.Scale,
            MouseFilter = MouseFilterEnum.Ignore,
            Modulate = new Color(1f, 1f, 1f, 0f),
            Visible = false,
        };
        rect.SetAnchorsPreset(LayoutPreset.FullRect);
        AddChild(rect);
        return rect;
    }

    private void BuildFlashoverFlash()
    {
        _flashoverFlash = new ColorRect
        {
            Name = "FlashoverFlash",
            Color = new Color(1f, 0.94f, 0.72f, 0f),
            Visible = false,
            MouseFilter = MouseFilterEnum.Ignore,
        };
        _flashoverFlash.SetAnchorsPreset(LayoutPreset.FullRect);
        AddChild(_flashoverFlash);
    }

    /// <summary>
    /// The branch changed. An empty name means there is no branch any more,
    /// which is the only way this HUD can know the Crucible ended: room 4's
    /// door is an ordinary exit and says nothing about leaving.
    ///
    /// A heat broadcast is what actually reveals the bar. Every branching
    /// portal emits this signal -- the Catacombs and the Act II shortcut
    /// included -- and only one of them is ever followed by a HeatChanged. So
    /// the HUD never names the branch it is drawing, which is the point: it
    /// consumes the vocabulary and holds no opinion about the world.
    /// </summary>
    private void OnBranchEntered(string branchName)
    {
        _inBranch = !string.IsNullOrEmpty(branchName);

        if (_inBranch) return;

        _heat01 = 0f;
        _alarmTime = 0f;
        SetHeatVisible(false);
        SetStreak(0);
    }

    private void OnHeatChanged(float heat01, int state)
    {
        if (!_inBranch) return;

        _heat01 = Mathf.Clamp(heat01, 0f, 1f);

        if (state != _heatState)
        {
            _heatState = state;
            // Transition from wherever the colour actually IS, not from the
            // previous state's nominal colour: a state that changes twice
            // inside 0.25s would otherwise jump.
            _heatColorFrom = CurrentHeatColor();
            _heatColorTo = HeatColors[Mathf.Clamp(state, 0, HeatColors.Length - 1)];
            _heatColorT = 0f;
        }

        SetHeatVisible(true);
    }

    private void SetHeatVisible(bool visible)
    {
        if (_heatBar != null) _heatBar.Visible = visible;
        if (_streakPips == null) return;
        foreach (var pip in _streakPips) pip.Visible = visible;
    }

    private Color CurrentHeatColor() => _heatColorFrom.Lerp(_heatColorTo, Mathf.Clamp(_heatColorT, 0f, 1f));

    private void OnParryStreakChanged(int streak) => SetStreak(streak);

    private void SetStreak(int streak)
    {
        if (_streakPips == null) return;
        for (int i = 0; i < _streakPips.Length; i++)
            _streakPips[i].Color = PipColor(i < streak);
    }

    /// <summary>
    /// A full-screen white-hot flash. The camera shake is NOT here: shaking the
    /// view is the camera's business, and it listens to the same signal. A HUD
    /// that reached for the camera would be the one place in this project where
    /// the interface touches a gameplay node.
    /// </summary>
    private void OnFlashover(Vector3 atPosition)
    {
        if (_flashoverFlash == null || !IsInsideTree()) return;

        _flashoverFlash.Visible = true;
        _flashoverFlash.Color = new Color(1f, 0.94f, 0.72f, 0.55f);

        var tween = CreateTween();
        if (tween == null) return;
        tween.TweenProperty(_flashoverFlash, "color:a", 0f, 0.42f)
             .SetTrans(Tween.TransitionType.Quad)
             .SetEase(Tween.EaseType.Out);
        tween.TweenCallback(Callable.From(() =>
        {
            if (_flashoverFlash != null && IsInstanceValid(_flashoverFlash))
                _flashoverFlash.Visible = false;
        }));
    }

    /// <summary>
    /// Layout and animation for the heat row.
    ///
    /// Position is recomputed from the health bar's global rect every frame
    /// rather than once at _Ready. Control layout settles over the first
    /// frames and again on every window resize, and a bar placed once sits
    /// where the health bar USED to be.
    /// </summary>
    public override void _Process(double delta)
    {
        // The overlays run FIRST and unconditionally. They are not part of the
        // heat row and must keep working outside the Crucible -- the low-health
        // vignette is the one piece of feedback that matters most in a room
        // with no heat bar in it at all.
        TickTensionOverlays((float)delta);

        if (_heatBar == null || _healthBar == null) return;
        if (!_heatBar.Visible) return;

        float dt = (float)delta;

        LayoutHeatRow();

        if (_heatColorT < 1f)
            _heatColorT = Mathf.Min(1f, _heatColorT + dt / HeatColorTransitionSeconds);

        _heatBar.Value = _heat01 * 100f;
        _heatFill.BgColor = CurrentHeatColor();

        // The alarm. Three hertz, and only in the last tenth of the bar: a
        // pulse that ran the whole time would be wallpaper by the second room.
        if (_heat01 >= AlarmAt)
        {
            _alarmTime += dt;
            float pulse = 0.55f + 0.45f * Mathf.Sin(_alarmTime * Mathf.Tau * 3f);
            _heatBar.Modulate = new Color(1f, 1f, 1f, 0.55f + 0.45f * pulse);
        }
        else
        {
            _alarmTime = 0f;
            _heatBar.Modulate = Colors.White;
        }
    }

    /// <summary>
    /// Both overlays, driven by a shared clock.
    ///
    /// One sine per overlay and two alpha writes: no tween is created, no
    /// texture is rebuilt, and nothing is allocated. The two pulse rates are
    /// deliberately different multiples of the same time base -- 1.2Hz and 3Hz
    /// -- so a player who is both nearly dead and about to be caught in a
    /// flashover sees two rhythms rather than one blur.
    ///
    /// Each target alpha is approached rather than assigned. A vignette that
    /// snapped on the frame health crossed 25% would read as a rendering
    /// glitch; these are moods, and a mood arrives.
    /// </summary>
    private void TickTensionOverlays(float dt)
    {
        if (_lowHealthVignette == null || _flashoverEdge == null) return;

        _overlayTime += dt;

        // -- low health ----------------------------------------------------
        bool lowHealth = _currentHealth > 0
                      && MaxHealth > 0
                      && _currentHealth <= MaxHealth * LowHealthFraction;

        float lowTarget = 0f;
        if (lowHealth)
        {
            // 0..1 rather than -1..1: the vignette breathes in and out of
            // clear, never darker-than-off.
            float pulse = 0.5f + 0.5f * Mathf.Sin(_overlayTime * Mathf.Tau * LowHealthPulseHz);
            lowTarget = pulse * LowHealthPeakAlpha;
        }

        _lowHealthAlpha = Mathf.MoveToward(_lowHealthAlpha, lowTarget, OverlayFadeSpeed * dt);
        ApplyOverlayAlpha(_lowHealthVignette, _lowHealthAlpha);

        // -- flashover -----------------------------------------------------
        // State 3 is HeatState.Flashover. Compared as the int the signal
        // carries, because the HUD holds no compile-time dependency on World
        // and the whole reason HeatChanged flattens the enum is so it does not
        // need one.
        bool flashover = _heatBar != null && _heatBar.Visible && _heatState == 3;

        float edgeTarget = 0f;
        if (flashover)
        {
            float pulse = 0.5f + 0.5f * Mathf.Sin(_overlayTime * Mathf.Tau * FlashoverPulseHz);
            edgeTarget = (0.45f + 0.55f * pulse) * FlashoverPeakAlpha;
        }

        _flashoverAlpha = Mathf.MoveToward(_flashoverAlpha, edgeTarget, OverlayFadeSpeed * dt);
        ApplyOverlayAlpha(_flashoverEdge, _flashoverAlpha);
    }

    /// Hidden at zero rather than merely transparent. A fully transparent
    /// full-screen TextureRect is still a quad the renderer blends every frame,
    /// and there are two of them.
    private static void ApplyOverlayAlpha(TextureRect rect, float alpha)
    {
        bool on = alpha > 0.002f;
        rect.Visible = on;
        if (!on) return;

        var m = rect.Modulate;
        m.A = alpha;
        rect.Modulate = m;
    }

    private void LayoutHeatRow()
    {
        var origin = GetGlobalRect().Position;
        var health = _healthBar.GetGlobalRect();

        const float barHeight = 10f;
        const float gap = 4f;
        const float pipSize = 9f;
        const float pipGap = 4f;

        float width = health.Size.X * 0.6f;
        var pos = health.Position - origin + new Vector2(0f, health.Size.Y + gap);

        _heatBar.Position = pos;
        _heatBar.Size = new Vector2(width, barHeight);

        // Marks at 40 and 70, in the bar's own space, two pixels wide.
        _heatTick40.Position = new Vector2(width * 0.40f, 0f);
        _heatTick40.Size = new Vector2(2f, barHeight);
        _heatTick70.Position = new Vector2(width * 0.70f, 0f);
        _heatTick70.Size = new Vector2(2f, barHeight);

        // Pips beside the HEALTH bar, not the heat bar: the streak is about
        // staying alive, and it belongs next to the number it protects.
        var pipOrigin = health.Position - origin + new Vector2(health.Size.X + 10f, (health.Size.Y - pipSize) * 0.5f);
        for (int i = 0; i < _streakPips.Length; i++)
        {
            _streakPips[i].Position = pipOrigin + new Vector2(i * (pipSize + pipGap), 0f);
            _streakPips[i].Size = new Vector2(pipSize, pipSize);
        }
    }

    private void BuildEmbersCounter()
    {
        _embersCounter = new Label
        {
            Name = "EmbersCounter",
            Text = "0 🔥",
            HorizontalAlignment = HorizontalAlignment.Right,
            MouseFilter = MouseFilterEnum.Ignore,
        };
        _embersCounter.SetAnchorsPreset(LayoutPreset.TopRight);
        _embersCounter.AnchorLeft = 1f;
        _embersCounter.AnchorRight = 1f;
        _embersCounter.OffsetLeft = -180f;
        _embersCounter.OffsetTop = 18f;
        _embersCounter.OffsetRight = -24f;
        _embersCounter.OffsetBottom = 44f;
        _embersCounter.AddThemeColorOverride("font_color", new Color(1.0f, 0.75f, 0.25f));
        _embersCounter.AddThemeColorOverride("font_outline_color", new Color(0f, 0f, 0f, 0.85f));
        _embersCounter.AddThemeConstantOverride("outline_size", 5);
        _embersCounter.AddThemeFontSizeOverride("font_size", 16);
        AddChild(_embersCounter);

        UpdateEmbersDisplay(Save.SaveManager.Instance?.Current?.TotalEmbers ?? 0);
    }

    private void BuildRuneModal()
    {
        _runeModal = new RuneForgeModal { Name = "RuneForgeModal" };
        AddChild(_runeModal);
    }

    private void OnEmbersChanged(int total) => UpdateEmbersDisplay(total);

    private void UpdateEmbersDisplay(int total)
    {
        if (_embersCounter != null && IsInstanceValid(_embersCounter))
            _embersCounter.Text = $"{total} 🔥";
        _runeModal?.RefreshUI();
    }

    private void OnRuneForgeRequested(bool open)
    {
        if (open) _runeModal?.Open();
        else _runeModal?.Close();
    }
