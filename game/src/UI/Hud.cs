    // -- The Crucible ------------------------------------------------------

    /// The four state colours, in HeatState order. Indexed by the int the
    /// signal carries, so a state added later fails loudly at the index rather
    /// than silently drawing the wrong colour.
    private static readonly Color[] HeatColors =
    {
        new(0.42f, 0.29f, 0.20f),   // Tempered  #6B4A32 dull iron
        new(0.88f, 0.54f, 0.17f),   // Kindled   #E08A2C amber
        new(1.00f, 0.35f, 0.15f),   // Molten    #FF5A26 orange-red
        new(1.00f, 0.82f, 0.29f),   // Flashover #FFD24A white-hot
    };

    /// Where the warning starts, as a fraction of the bar. Two and a half
    /// seconds of notice at the branch's worst gain rate, which is the whole
    /// point: an alarm that fires as the thing happens is a report, not a
    /// warning.
    private const float AlarmAt = 0.90f;

    private const float HeatColorTransitionSeconds = 0.25f;
    private const int StreakPips = 4;

    private ProgressBar _heatBar;
    private StyleBoxFlat _heatFill;
    private ColorRect _heatTick40;
    private ColorRect _heatTick70;
    private ColorRect[] _streakPips;
    private ColorRect _flashoverFlash;

    // -- Full-screen tension overlays ---------------------------------------
    //
    // Two radial gradients that live at the edges of the frame and stay out of
    // the middle of it. Both are built once, in _Ready, and animated by writing
    // a single Modulate alpha per frame -- no tween objects created per pulse,
    // no textures rebuilt, nothing allocated after startup.
    //
    // GradientTexture2D rather than a shader or an imported PNG: the gradient
    // is generated by the engine from four numbers, which keeps the project's
    // "no external asset files" rule intact and leaves the falloff tunable
    // without opening an image editor.

    /// #8A0B0B. Dark and desaturated on purpose -- a bright red vignette reads
    /// as a damage flash, and this is a STATE, not an event.
    private static readonly Color LowHealthColor = new(0.541f, 0.043f, 0.043f);

    /// #FF9515.
    private static readonly Color FlashoverEdgeColor = new(1f, 0.584f, 0.082f);

    /// 1.2Hz, matched to the low-health heartbeat in AudioManager. The eye and
    /// the ear reporting the same fact on the same beat is what makes it read
    /// as one warning rather than two problems.
    [Export] public float LowHealthPulseHz { get; set; } = 1.2f;
    [Export] public float LowHealthPeakAlpha { get; set; } = 0.35f;
    [Export] public float LowHealthFraction { get; set; } = 0.25f;

    /// 3Hz, matched to the heat bar's own alarm and to the audio sizzle.
    [Export] public float FlashoverPulseHz { get; set; } = 3f;
    [Export] public float FlashoverPeakAlpha { get; set; } = 0.40f;

    /// How fast an overlay fades once its condition stops holding. Not
    /// instant: a vignette that vanishes on the frame a heal lands reads as a
    /// glitch, and the whole point of these is that they are moods.
    [Export] public float OverlayFadeSpeed { get; set; } = 3.2f;

